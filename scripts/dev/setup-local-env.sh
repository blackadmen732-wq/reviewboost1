#!/usr/bin/env bash
#
# Write frontend/.env.local for local development against the local Supabase
# stack. Safe to run repeatedly: the local anon/service keys are refreshed from
# `supabase status` every time, while the development-only encryption keys are
# generated once and then preserved so existing encrypted rows stay readable.
#
# Nothing written here is a production secret. The anon/service keys are the
# well-known local Supabase demo keys, and the encryption keys are freshly
# generated values that only ever protect a throwaway local database.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
env_file="$repo_root/frontend/.env.local"

# Pull connection details from the running local stack.
status_env="$(cd "$repo_root" && npx --yes supabase status -o env)"
get() { printf '%s\n' "$status_env" | sed -n "s/^$1=\"\(.*\)\"$/\1/p"; }

api_url="$(get API_URL)"
anon_key="$(get ANON_KEY)"
service_role_key="$(get SERVICE_ROLE_KEY)"

if [[ -z "$api_url" || -z "$anon_key" || -z "$service_role_key" ]]; then
  echo "Could not read Supabase status. Is the local stack running (supabase start)?" >&2
  exit 1
fi

# Preserve an existing development encryption key so previously encrypted rows
# remain decryptable across reboots; otherwise mint a fresh one.
existing_key=""
if [[ -f "$env_file" ]]; then
  existing_key="$(sed -n 's/^CUSTOMER_NOTE_ENCRYPTION_KEY=//p' "$env_file" | head -n1)"
fi
encryption_key="${existing_key:-$(openssl rand -base64 32)}"

cat > "$env_file" <<EOF
# Generated by scripts/dev/setup-local-env.sh for local development.
# Gitignored. Not production secrets — local Supabase demo keys plus a
# development-only encryption key protecting a throwaway local database.

NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon_key
SUPABASE_URL=$api_url
SUPABASE_ANON_KEY=$anon_key
SUPABASE_SERVICE_ROLE_KEY=$service_role_key

CUSTOMER_NOTE_ENCRYPTION_KEY=$encryption_key
TOKEN_DIGEST_KEY_VERSION=1

PUBLIC_FRONTEND_URL=http://localhost:3000
NEXT_PUBLIC_USE_CUSTOMER_FIXTURES=false
NEXT_PUBLIC_API_BASE_URL=

SMS_PROVIDER=fake
EOF

echo "Wrote $env_file"
