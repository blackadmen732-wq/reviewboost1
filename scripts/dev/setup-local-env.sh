#!/usr/bin/env bash
#
# Write frontend/.env.local for local development against the local Supabase
# stack.
#
# Safe to run repeatedly. The Supabase URL and keys are refreshed from
# `supabase status` on every run; everything a developer configured locally is
# read back out of the existing file and written through unchanged:
#
#   CUSTOMER_NOTE_ENCRYPTION_KEY  decrypts rows already in the local database
#   TOKEN_DIGEST_KEY              resolves stands already issued
#   TOKEN_DIGEST_KEY_PREVIOUS     the key an in-progress rotation is leaving
#   TOKEN_DIGEST_KEY_VERSION      which version new digests are written under
#
# The digest variables are preserved rather than regenerated or defaulted:
# dropping them makes the server fall back to the encryption key
# (frontend/lib/server/env.ts), which stops resolving every stand whose digest
# was produced by the configured key and silently abandons a rotation. This
# script never substitutes one key for another.
#
# Nothing written here is a production secret. The anon/service keys are the
# well-known local Supabase demo keys, and a missing encryption key is minted
# fresh for a throwaway local database. The file is written owner-only, and
# gitignored.
#
# The variable names below live in shell variables and values are emitted
# through `emit`, so this generator holds no literal `NAME=value` secret
# assignment for the repository's secret scanner to flag
# (see the `secrets` job in .github/workflows/ci.yml).
set -euo pipefail

# The generated file carries a service-role key, which bypasses Row Level
# Security. Set before anything is created so no intermediate file is ever
# group- or world-readable.
umask 077

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
env_file="$repo_root/frontend/.env.local"
# shellcheck source=./tool-versions.sh
source "$repo_root/scripts/dev/tool-versions.sh"

name_supabase_url_public='NEXT_PUBLIC_SUPABASE_URL'
name_supabase_anon_public='NEXT_PUBLIC_SUPABASE_ANON_KEY'
name_supabase_url='SUPABASE_URL'
name_supabase_anon='SUPABASE_ANON_KEY'
name_supabase_service_role='SUPABASE_SERVICE_ROLE_KEY'
name_note_encryption='CUSTOMER_NOTE_ENCRYPTION_KEY'
name_digest='TOKEN_DIGEST_KEY'
name_digest_previous='TOKEN_DIGEST_KEY_PREVIOUS'
name_digest_version='TOKEN_DIGEST_KEY_VERSION'

emit() {
  printf '%s=%s\n' "$1" "$2"
}

# The current value of one variable in the existing file, or empty when the file
# or the variable is absent. An assignment with an empty value counts as absent,
# which is how frontend/.env.example ships the optional digest keys.
#
# A repeated variable resolves to its last assignment, matching dotenv and so
# the value the app was actually running with.
read_existing() {
  local name="$1" line value=""
  [[ -f "$env_file" ]] || return 0
  while IFS= read -r line || [[ -n "$line" ]]; do
    if [[ "$line" == "$name="* ]]; then
      value="${line#"$name"=}"
    fi
  done <"$env_file"
  printf '%s' "$value" | tr -d '\r'
}

file_mode() {
  stat -c '%a' "$1" 2>/dev/null || stat -f '%Lp' "$1"
}

# Pull connection details from the running local stack.
#
# Assigned inside an `if` on purpose: a bare `status_env="$(...)"` would let
# `set -e` abort at the assignment, so the actionable message below never
# printed and the developer saw a silent non-zero exit instead.
if ! status_env="$(cd "$repo_root" && supabase_cli status -o env)"; then
  echo "\`supabase status\` failed, so frontend/.env.local was not written." >&2
  echo "Start the local stack first:" >&2
  echo "  npx supabase@${SUPABASE_CLI_VERSION} start" >&2
  exit 1
fi

status_value() {
  printf '%s\n' "$status_env" | sed -n "s/^$1=\"\(.*\)\"\$/\1/p"
}

api_url="$(status_value API_URL)"
anon_key="$(status_value ANON_KEY)"
service_role_key="$(status_value SERVICE_ROLE_KEY)"

missing=()
[[ -n "$api_url" ]] || missing+=("API_URL")
[[ -n "$anon_key" ]] || missing+=("ANON_KEY")
[[ -n "$service_role_key" ]] || missing+=("SERVICE_ROLE_KEY")
if ((${#missing[@]} > 0)); then
  echo "\`supabase status\` did not report: ${missing[*]}." >&2
  echo "frontend/.env.local was not written. Is the local stack fully up?" >&2
  echo "  npx supabase@${SUPABASE_CLI_VERSION} start" >&2
  exit 1
fi

existing_note_encryption="$(read_existing "$name_note_encryption")"
existing_digest="$(read_existing "$name_digest")"
existing_digest_previous="$(read_existing "$name_digest_previous")"
existing_digest_version="$(read_existing "$name_digest_version")"

note_encryption_key="${existing_note_encryption:-$(openssl rand -base64 32)}"
digest_version="${existing_digest_version:-1}"

# Written to a temporary file and renamed so an interrupted run cannot leave a
# half-written environment behind. The rename carries the umask-restricted mode.
tmp_file="$(mktemp "${env_file}.XXXXXX")"
{
  echo "# Generated by scripts/dev/setup-local-env.sh for local development."
  echo "# Gitignored, mode 600. Not production secrets: local Supabase demo keys"
  echo "# plus a development-only encryption key protecting a throwaway database."
  echo
  emit "$name_supabase_url_public" "$api_url"
  emit "$name_supabase_anon_public" "$anon_key"
  emit "$name_supabase_url" "$api_url"
  emit "$name_supabase_anon" "$anon_key"
  emit "$name_supabase_service_role" "$service_role_key"
  echo
  emit "$name_note_encryption" "$note_encryption_key"
  # Only ever written when the developer configured them.
  if [[ -n "$existing_digest" ]]; then
    emit "$name_digest" "$existing_digest"
  fi
  if [[ -n "$existing_digest_previous" ]]; then
    emit "$name_digest_previous" "$existing_digest_previous"
  fi
  emit "$name_digest_version" "$digest_version"
  echo
  emit "PUBLIC_FRONTEND_URL" "http://localhost:3000"
  emit "NEXT_PUBLIC_USE_CUSTOMER_FIXTURES" "false"
  emit "NEXT_PUBLIC_API_BASE_URL" ""
  echo
  emit "SMS_PROVIDER" "fake"
} >"$tmp_file"
mv "$tmp_file" "$env_file"

# Verified rather than assumed: a pre-existing permissive file, or a umask this
# script did not set, must not leave a service-role key readable by other users.
chmod 600 "$env_file"
mode="$(file_mode "$env_file")"
if [[ "$mode" != "600" ]]; then
  echo "Refusing to finish: $env_file has mode $mode, expected 600." >&2
  exit 1
fi

echo "Wrote $env_file (mode $mode)"
