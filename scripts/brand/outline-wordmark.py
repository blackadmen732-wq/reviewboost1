#!/usr/bin/env python3
"""Outline the ReviewBoost wordmark into Branding/Wordmark.svg.

The wordmark is Geist SemiBold, the product's own face, set as the web header
sets it: "Review" and "Boost" as one word, the font's own kerning, and a
-0.02em track. Live text is right inside the product; a file that leaves it
(an OG image, a press kit, the lockup SVG) cannot count on Geist being
installed, so the letters are converted to outlines once, here.

Run only when the wordmark itself changes:

    pip install fonttools uharfbuzz
    python3 scripts/brand/outline-wordmark.py
    node scripts/brand/generate-brand-assets.mjs

Uses the Geist files the frontend already installs (`npm ci` in frontend/).
"""
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "frontend/node_modules/geist/dist/fonts/geist-sans/Geist-SemiBold.ttf"
OUT = ROOT / "Branding/Wordmark.svg"

SIZE = 100          # font size in SVG units
TRACK = -0.02       # em, matches the header's tracking
INK = "#171A18"     # --rb-ink
GREEN = "#00A86B"   # --rb-brand, the one ReviewBoost green


def shape(text: str, face: hb.Face, font: hb.Font):
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})
    return buf.glyph_infos, buf.glyph_positions


def fmt(value: float) -> str:
    return f"{value:.2f}".rstrip("0").rstrip(".")


def main() -> None:
    blob = hb.Blob.from_file_path(str(FONT))
    face = hb.Face(blob)
    font = hb.Font(face)
    tt = TTFont(str(FONT))
    upem = tt["head"].unitsPerEm
    glyph_set = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    scale = SIZE / upem
    ascent = tt["hhea"].ascent * scale
    cap = tt["OS/2"].sCapHeight * scale

    # Shape the whole name at once so the kern across "w|B" is the font's own.
    infos, positions = shape("ReviewBoost", face, font)
    x = 0.0
    parts = {"Review": [], "Boost": []}
    for index, (info, pos) in enumerate(zip(infos, positions)):
        pen = SVGPathPen(glyph_set)
        # Font units are y-up; flip onto a baseline at `ascent`.
        tpen = TransformPen(pen, (scale, 0, 0, -scale, x + pos.x_offset * scale, ascent))
        glyph_set[order[info.codepoint]].draw(tpen)
        parts["Review" if index < 6 else "Boost"].append(pen.getCommands())
        x += pos.x_advance * scale + TRACK * SIZE
    width = x - TRACK * SIZE

    # Crop to the letters: cap height plus the round letters' overshoot, so a
    # lockup can align the wordmark by its box without knowing font metrics.
    overshoot = 0.015 * SIZE
    top = ascent - cap - overshoot
    height = cap + 2 * overshoot
    box = f"0 {fmt(top)} {fmt(width)} {fmt(height)}"
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" width="{fmt(width)}" height="{fmt(height)}" role="img" aria-labelledby="rb-wordmark-title">
<!-- Generated by scripts/brand/outline-wordmark.py from Geist SemiBold, the product face. Do not edit by hand. -->
<title id="rb-wordmark-title">ReviewBoost</title>
<path fill="{INK}" d="{' '.join(parts['Review'])}"/>
<path fill="{GREEN}" d="{' '.join(parts['Boost'])}"/>
</svg>
"""
    OUT.write_text(svg)
    print(f"wrote {OUT.relative_to(ROOT)} ({fmt(width)} x {fmt(ascent)}, cap {fmt(cap)})")


if __name__ == "__main__":
    main()
